def load_sheet(path, sheet, prefix, meta, src):
    ws = openpyxl.load_workbook(path, data_only=True)[sheet]; out = []
    for row in ws.iter_rows(values_only=True):
        if not row or not isinstance(row[0], str) or not row[0].startswith(prefix) or not row[1]: continue
        code, name, q, scene, lvl, contact = (list(row) + [None]*6)[:6]
        step, tag = meta[code]
        out.append((code, name, q, scene or "", lvl or "一般", contact or "", step, tag, src))
    return out

